inline bool IsWhitespace(UChar32 code_point) noexcept {
    return std::binary_search(kWhitespace.begin(), kWhitespace.end(),
                              code_point);
}

inline bool IsPunctuation(UChar32 code_point) noexcept {
    return std::binary_search(kPunctuation.begin(), kPunctuation.end(),
                              code_point);
}

inline bool IsSeparator(char32_t code_point) noexcept {
    const auto value = static_cast<UChar32>(code_point);
    return IsWhitespace(value) || IsPunctuation(value);
}

